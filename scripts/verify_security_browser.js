  // File upload supplies the local test credential without embedding or logging
  // its value in this script, command output, snapshots, or browser storage.
  await page.evaluate(() => { const i=document.createElement('input'); i.type='file'; i.id='test-credential-file'; document.querySelector('#operator-form').append(i); });
  await page.locator('#test-credential-file').setInputFiles('C:/Users/acer/Desktop/GraphHacks/artifacts/.operator-token');

async (page) => {
  const errors=[];
  page.on('pageerror', e=>errors.push(e.message));
  await page.setViewportSize({width:1440,height:1000});
  await page.goto('http://127.0.0.1:8000/amb.html');
  await page.locator('#connection').filter({hasText:'Company connected'}).waitFor();
  if(await page.locator('#risk-count').innerText()!=='6')throw new Error('Expected six distinct workstreams');
  if(await page.locator('#event-count').innerText()!=='37')throw new Error('Expected 37 scheduled events');
  await page.locator('#customer-proof').click();
  await page.locator('#evidence-body').filter({hasText:'Our launch depends on it'}).waitFor();
  await page.locator('#close-evidence').click();
  await page.locator('[data-filter="customer"]').click();
  if(await page.locator('#work-list .work-row').count()!==1)throw new Error('Customer filter failed');
  await page.locator('[data-filter="all"]').click();
  await page.locator('[data-view="people"]').click();
  if(await page.locator('.person-card').count()!==9)throw new Error('People directory missing teammates');
  await page.locator('#search').fill('Tariq');
  await page.locator('#search-results button').click();
  await page.locator('#evidence-body h2').filter({hasText:'Tariq Osei'}).waitFor();
  await page.locator('#close-evidence').click();
  await page.locator('#search').fill('');
  await page.locator('[data-view="customers"]').click();
  await page.locator('#customer-proof-full').click();
  await page.locator('#evidence-body').filter({hasText:'CSV export encoding'}).waitFor();
  await page.locator('#close-evidence').click();
  await page.locator('[data-view="handover"]').click();
  await page.locator('#capacity').click();
  await page.locator('#capacity-result').filter({hasText:'Suggested 6 of 6'}).waitFor();
  if(await page.locator('#assignments select').evaluateAll(items=>items.filter(i=>i.value).length)!==6)throw new Error('Suggested owners did not populate');
  await page.locator('#replay').click();
  await page.locator('#review-heading').filter({hasText:'The plan covers the scheduled work'}).waitFor();
  const downloadPromise=page.waitForEvent('download');
  await page.locator('#download-brief').click();
  const download=await downloadPromise;
  if(download.suggestedFilename()!=='Halden-Hana-handover.txt')throw new Error('Brief download failed');
  await download.saveAs('output/playwright/Halden-Hana-handover.txt');
  await page.locator('#write').click();
  await page.locator('#operator-dialog').waitFor({state:'visible'});
  await page.locator('#close-operator').click();
  await page.screenshot({path:'output/playwright/company-handover.png',fullPage:true});
  await page.locator('[data-view="overview"]').click();
  await page.screenshot({path:'output/playwright/company-desktop.png',fullPage:true});
  await page.setViewportSize({width:390,height:844});
  await page.screenshot({path:'output/playwright/company-mobile.png',fullPage:true});
  const width=await page.evaluate(()=>({page:document.documentElement.scrollWidth,viewport:innerWidth}));
  if(width.page>width.viewport)throw new Error('Mobile overflow');
  await page.locator('#mobile-view').selectOption('people');
  await page.locator('#view-people').waitFor({state:'visible'});
  await page.locator('#mobile-view').selectOption('handover');
  await page.locator('#view-handover').waitFor({state:'visible'});
  await page.locator('#mobile-view').selectOption('overview');
  if(errors.length)throw new Error(errors.join('; '));
  await page.setViewportSize({width:1440,height:1000});
  return {story:'6 responsibilities / 37 events',people:9,customerEvidence:'verified',suggestion:'6/6',preview:'all covered; no live write',download:'handover brief',mobile:width,errors};
}

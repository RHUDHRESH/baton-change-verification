async (page) => {
  const errors=[];
  page.on('pageerror',e=>errors.push(e.message));
  await page.context().clearCookies();
  await page.goto('http://127.0.0.1:8001/');
  await page.locator('#connection').filter({hasText:'Company connected'}).waitFor();
  await page.locator('#start-handover').click();
  await page.locator('#capacity').click();
  await page.locator('#capacity-result').filter({hasText:'Suggested 6 of 6'}).waitFor();
  await page.locator('#replay').click();
  await page.locator('#review-heading').filter({hasText:'The plan covers'}).waitFor();
  await page.locator('#write').click();
  await page.locator('#operator-dialog').waitFor({state:'visible'});
  await page.evaluate(()=>{const input=document.createElement('input');input.type='file';input.id='test-token';document.querySelector('#operator-form').append(input);});
  await page.locator('#test-token').setInputFiles('C:/Users/acer/Desktop/GraphHacks/artifacts/.operator-token');
  await page.evaluate(async()=>{const input=document.getElementById('test-token');document.getElementById('operator-token').value=(await input.files[0].text()).trim();input.remove();});
  await page.getByRole('button',{name:'Sign in',exact:true}).click();
  await page.locator('#operator').filter({hasText:'sign out'}).waitFor();
  await page.locator('#write').filter({hasText:'Save reviewed handover'}).waitFor();
  await page.locator('#consent').check();
  await page.locator('#write').click();
  await page.locator('#receipt strong').filter({hasText:'Handover saved and verified'}).waitFor();
  await page.locator('[data-view="overview"]').click();
  if(await page.locator('#risk-count').innerText()!=='0')throw new Error('Overview did not reflect saved coverage');
  await page.locator('[data-view="activity"]').click();
  await page.getByRole('button',{name:'View the verification receipt'}).click();
  await page.locator('#evidence-body').filter({hasText:'Ownership saved and verified'}).waitFor();
  await page.locator('#close-evidence').click();
  await page.reload();
  await page.locator('#connection').filter({hasText:'Company connected'}).waitFor();
  await page.locator('.activity-card h3').filter({hasText:'6 responsibilities handed over'}).waitFor();
  await page.screenshot({path:'output/playwright/company-saved-handover.png',fullPage:true});
  await page.locator('[data-view="tasks"]').click();
  await page.locator('#create-task').click();
  await page.locator('#task-title').fill('Review Oaktree’s CSV fix with Bao');
  await page.locator('#task-owner').selectOption({index:1});
  await page.locator('#task-due').fill('2026-11-03');
  await page.locator('#task-notes').fill('Check the expected encoding before the customer launch.');
  await page.getByRole('button',{name:'Create task',exact:true}).click();
  await page.locator('.task-card h3').filter({hasText:'Review Oaktree'}).waitFor();
  await page.getByRole('button',{name:'Mark done',exact:true}).click();
  await page.getByRole('button',{name:'Reopen task',exact:true}).waitFor();
  await page.reload();
  await page.getByRole('button',{name:'Reopen task',exact:true}).waitFor();
  if(errors.length)throw new Error(errors.join('; '));
  return {saved:6,uncovered:0,receipt:'verified',reload:'persisted',task:'created, assigned, completed and persisted',errors};
}

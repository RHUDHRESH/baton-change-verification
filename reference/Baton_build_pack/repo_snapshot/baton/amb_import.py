"""`python -m baton amb-import --seed S --steps N --out DIR`: a second, externally-written test company.

The company comes from agent-memory-bench by Liz Zhang (MIT, https://github.com/zhang-liz/agent-memory-bench),
vendored unmodified in third_party/amb. Its facts (who owns which service, who holds which team's pager) arrive only
as free text: Slack lines, tickets, emails, incident reports. That is the point: Baton's records here are empty, so
everything has to come from reading.

DIR/world.json is a Baton world (same schema as `generate`): people, one on-call duty per team with weekly handover
events in the window, no records, every amb inbox item as a message (Slack-shaped) or a ticket (ticket, email,
incident, doc). The "attached logs" block amb appends to each item is dropped. The generator's sealed truth (final
state, per-item asserts/retracts, questions with answers) goes to DIR/amb_truth.json and never into world.json.
Output is deterministic: same seed and steps, same bytes.
"""
import json
import re
import sys
from datetime import timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DAY = 86_400_000
HOUR = 3_600_000
WINDOW_DAYS = 30
CREDIT = ("Company generated by agent-memory-bench (amb/world.py) by Liz Zhang, MIT License, "
          "https://github.com/zhang-liz/agent-memory-bench; vendored in third_party/amb")
SLACK = re.compile(r"^\[(#[^\]]+)\] ([^:\n]+): (.*)$", re.S)


def _amb():
    if str(ROOT) not in sys.path:
        sys.path.insert(0, str(ROOT))
    from third_party.amb import world
    return world


def _ms(dt):
    return int(dt.replace(tzinfo=timezone.utc).timestamp() * 1000)


def _pid(name):
    return "".join(c if c.isalnum() else "." for c in name.lower()).strip(".")


def _slug(s):
    return "".join(c if c.isalnum() else "-" for c in s.lower()).strip("-")


def _entities(aw):
    services = sorted({v for k, v in aw.aliases.items() if k.startswith("the ") and k.endswith(" service")})
    teams = sorted({v for v in aw.aliases.values() if v.startswith("Team ")})
    people = sorted(set(aw.aliases.values()) - set(services) - set(teams))
    return services, teams, people


def _parse(text, ids):
    """Split one amb inbox item into ('message', fields) or ('ticket', fields). `ids` maps person name -> id."""
    body = text.split("\n\nattached logs:\n")[0].strip()
    who = lambda s: ids.get(s.strip(), s.strip())  # noqa: E731
    m = SLACK.match(body)
    if m:
        return "message", {"channel": m.group(1), "author": who(m.group(2)), "text": m.group(3).strip()}
    first = body.split("\n", 1)[0]
    if first.startswith("From: "):
        addr = first[len("From: "):].strip()
        local = addr.split("@")[0]
        return "ticket", {"author": ids.get(local.capitalize(), ids.get(local, addr)), "text": body}
    if first.startswith("INCIDENT "):
        hit = re.search(r"opened by (.+)$", first)
        return "ticket", {"author": who(hit.group(1)) if hit else "alerting", "text": body}
    if first.startswith("TICKET "):
        hit = re.search(r" from (\S+)$", first)
        return "ticket", {"author": who(hit.group(1)) if hit else "service-catalog", "text": body}
    return "ticket", {"author": "design-docs" if first.startswith("Design doc") else "unknown", "text": body}


def _state(s):
    return {"owner": dict(sorted(s["owner"].items())),
            "deps": {k: sorted(v) for k, v in sorted(s["deps"].items())},
            "members": dict(sorted(s["members"].items())), "oncall": dict(sorted(s["oncall"].items())),
            "incidents": [list(x) for x in s["incidents"]],
            "changed_owner": sorted(s["changed_owner"]), "changed_oncall": sorted(s["changed_oncall"])}


def build(seed, steps):
    """Return (world, truth) for an amb company. Pure: same arguments, same output."""
    amb = _amb()
    aw = amb.generate(seed, steps)
    services, teams, names = _entities(aw)
    ids = {n: _pid(n) for n in names}
    messages, tickets, by_step = [], [], {}
    for e in aw.events:
        kind, f = _parse(e.text, ids)
        row = dict(f, at=_ms(e.time))
        (messages if kind == "message" else tickets).append(row)
        by_step[e.step] = row
    for i, m in enumerate(messages, 1):
        m["id"] = f"msg-{i:04d}"
    for i, t in enumerate(tickets, 1):
        t["id"] = f"tkt-{i:04d}"
    last = max(_ms(e.time) for e in aw.events)
    now = last - last % DAY + DAY
    # the leaver: whoever the text talks about most (ties by name); chosen from the text, not from the truth
    texts = [r["text"] + " " + str(r["author"]) for r in messages + tickets]
    mentions = {n: sum(1 for t in texts if re.search(rf"\b{re.escape(n)}\b|\b{re.escape(ids[n])}\b", t))
                for n in names}
    leaver = ids[min(names, key=lambda n: (-mentions[n], n))]
    people = [{"id": ids[n], "name": n, "team": None, "role": None, "left_at": None} for n in names]
    duties, events = [], []
    for t in teams:
        did = f"d-oncall-{_slug(t.removeprefix('Team '))}"
        duties.append({"id": did, "name": f"{t} on-call", "kind": "oncall"})
        for k in range(6):
            at = now + (3 + 7 * k) * DAY + 9 * HOUR
            events.append({"duty": did, "at": at, "label": f"{t} on-call handover"})
    events.sort(key=lambda x: (x["at"], x["duty"]))
    for i, ev in enumerate(events, 1):
        ev["id"] = f"ev-{i:04d}"
    world = {
        "seed": f"amb-{seed}-{steps}", "label": "FIXTURE", "company": f"Acme (agent-memory-bench seed {seed})",
        "credit": CREDIT, "now": now, "day_ms": DAY, "window_days": WINDOW_DAYS, "leaver": leaver,
        "leave_at": now + DAY, "people": people, "duties": sorted(duties, key=lambda d: d["id"]), "records": [],
        "events": events, "messages": messages, "joblogs": [], "tickets": tickets,
        "services": services, "teams": teams,
    }
    truth = {
        "credit": CREDIT, "seed": seed, "steps": steps, "world_seed": world["seed"],
        "final_state": _state(aw.final_state),
        "items": [{"source": by_step[e.step]["id"], "step": e.step, "kind": e.kind,
                   "asserts": [list(a) for a in e.asserts], "retracts": [list(r) for r in e.retracts]}
                  for e in aw.events],
        "questions": [{"qid": q.qid, "after_step": q.after_step, "after_source": by_step[q.after_step]["id"],
                       "category": q.category, "text": q.text, "answer": q.answer} for q in aw.questions],
        "followup_questions": [{"qid": q.qid, "category": q.category, "text": q.text, "answer": q.answer}
                               for q in amb.followup_questions(aw)],
    }
    return world, truth


def run(seed, steps, out):
    world, truth = build(seed, steps)
    d = Path(out)
    d.mkdir(parents=True, exist_ok=True)
    (d / "world.json").write_text(json.dumps(world, sort_keys=True, indent=1) + "\n")
    (d / "amb_truth.json").write_text(json.dumps(truth, sort_keys=True, indent=1) + "\n")
    return {"seed": world["seed"], "out": str(d), "graph": f"halden_{world['seed']}", "leaver": world["leaver"],
            "counts": {k: len(world[k]) for k in ("people", "duties", "records", "events", "messages", "joblogs",
                                                  "tickets")},
            "questions": len(truth["questions"]), "credit": CREDIT}
